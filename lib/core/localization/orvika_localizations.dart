        'ru' => _russian, 'es' => _spanishDraft, 'hi' => _hindiDraft, 'de' => _germanDraft, 'fr' => _frenchDraft,
        'it' => _italianDraft, 'pa' => _punjabiDraft, 'ur' => _urduDraft,
        'ar' => _arabicDraft, 'mr' => _marathiDraft, 'gu' => _gujaratiDraft,
        'sa' => _sanskritDraft, 'pt' => _portugueseDraft, _ => const <String, String>{},
      };

  /// Phase-two checker strings override or extend the initial language packs.
  Map<String, String> get _translations => {
        ..._baseTranslations,
        ...OrvikaFeatureTranslations.forCode(language.code),
      };

  /// True only when the selected language contains an authored value for [key].
  bool hasTranslation(String key) => _translations.containsKey(key);

  /// Resolves a key using the existing positional-fallback API.
  String text(String key, [String? fallback]) =>
      _translations[key] ??
      OrvikaFeatureTranslations.forCode(language.code)[key] ??
      fallback ??
      key;

  /// Resolves a key and interpolates named placeholders such as {count}.
  /// Missing parameters remain visible to make incomplete call sites detectable.
  String textWithParameters(
    String key, {
    String? fallback,
    Map<String, Object?> parameters = const {},
  }) {
    final resolved = _translations[key] ??
        OrvikaFeatureTranslations.forCode(language.code)[key] ??
        fallback ??
        key;
    return resolved.replaceAllMapped(
      RegExp(r'\{([a-zA-Z][a-zA-Z0-9_]*)\}'),
      (match) {
        final name = match.group(1)!;
        return parameters.containsKey(name) ? '${parameters[name]}' : match.group(0)!;
      },
    );
  }

  static OrvikaLocalizations of(BuildContext context) {
    final selectedLanguage = OrvikaLanguageScope.maybeOf(context);
    if (selectedLanguage != null) {
      return OrvikaLocalizations(selectedLanguage);
    }
    final locale = Localizations.localeOf(context);
    return OrvikaLocalizations(OrvikaLanguage.fromCode(locale.languageCode));
  }
}

/// Carries ORVIKA's selected catalogue language independently of Flutter's
/// framework locale delegates, which do not provide Material translations for
/// every regional language in the 200-language picker.
class OrvikaLanguageScope extends InheritedWidget {
  const OrvikaLanguageScope({
    super.key,
    required this.language,
    required super.child,
  });

  final OrvikaLanguage language;

  static OrvikaLanguage? maybeOf(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<OrvikaLanguageScope>()?.language;

  @override
  bool updateShouldNotify(OrvikaLanguageScope oldWidget) =>
      language.code != oldWidget.language.code;
}
